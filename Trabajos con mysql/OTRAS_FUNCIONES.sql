-- Función para comprimir y descomprimir datos.
-- Evitar palabras reservadas


SELECT COMPRESS(prod.Prod_Descripcion) AS comprimido_descpción FROM productos prod

SELECT UNCOMPRESS(COMPRESS(prod.Prod_Descripcion)) AS original FROM productos prod 

-- Función concatenar
SELECT CONCAT_WS(" ",prod.Prod_Id, prod.Prod_Descripcion, prod.Prod_Color) AS descripcion FROM productos prod


-- Convertir en binario el número 10

SELECT CONV("10", 10,2)
SELECT CONV("A", 16,10)
